const dictionaries = { pt, en, es }

export const SUPPORTED_LOCALES = Object.keys(dictionaries) // ['pt', 'en', 'es']
export const DEFAULT_LOCALE = 'pt'

// Resolve a value using dot-notation. Returns undefined when missing.
function getByPath(obj, path) {
  if (!obj) return undefined
  return path.split('.').reduce((acc, part) => (acc && acc[part] !== undefined ? acc[part] : undefined), obj)
}

/** Translate a key with PT fallback. */
export function translate(locale, key) {
  const lang = dictionaries[locale] ? locale : DEFAULT_LOCALE
  const value = getByPath(dictionaries[lang], key)
  if (value !== undefined) return value
  // Fallback to PT
  const fallback = getByPath(dictionaries[DEFAULT_LOCALE], key)
  if (fallback !== undefined) return fallback
  // Last resort: return the key itself so missing strings are visible during dev.
  return key
}

export default dictionaries
